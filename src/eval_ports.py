"""Reference-free evaluation over UAE ports (no free 2.5 m ground truth exists for these dates).

For each port, date and method:
  - LR consistency  : SR area-downsampled to 10 m vs the Sentinel-2 input (PSNR, higher = more faithful)
  - detections      : YOLO11m-OBB (DOTA) counts per class (ship, harbor, storage tank, ...)
For each pair of dates (same MGRS tile -> pixel-aligned):
  - temporal instability on unchanged pixels: mean |SR_a - SR_b| where |bicubic_a - bicubic_b| < 3 grey
    levels. The input says "nothing changed here", so any SR difference was generated by the model.
    Reported relative to bicubic's own value (excess instability).

Usage:  python src/eval_ports.py --methods bicubic realesrgan satlas ft_l1 ft_gan
"""
import argparse
import glob
import itertools
import json
import os
import sys

import cv2
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from srlib import ROOT, WEIGHTS, bicubic, load_model, lr_consistency, sr_tiled  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--methods", nargs="+", default=["bicubic", "realesrgan", "satlas", "ft_l1", "ft_gan"])
    a = ap.parse_args()
    from ultralytics import YOLO
    det = YOLO(os.path.join(ROOT, "weights", "yolo11m-obb.pt"))
    models = {m: load_model(m) for m in a.methods if m != "bicubic" and os.path.exists(os.path.join(ROOT, WEIGHTS[m]))}
    rows, trows, detections = [], [], {}
    for port_dir in sorted(glob.glob(os.path.join(ROOT, "data", "s2_ports", "*", ""))):
        port = os.path.basename(os.path.dirname(port_dir))
        srs = {}
        for f in sorted(glob.glob(os.path.join(port_dir, "*_rgb.png"))):
            date = os.path.basename(f)[:10]
            lr = cv2.cvtColor(cv2.imread(f), cv2.COLOR_BGR2RGB)
            for m in a.methods:
                if m == "bicubic":
                    sr = bicubic(lr)
                elif m in models:
                    sr = sr_tiled(models[m], lr, tile=32 if m == "satlas" else 64, pad=4 if m == "satlas" else 8)
                else:
                    continue
                srs[(date, m)] = sr
                o = os.path.join(ROOT, "results", "ports", port, date)
                os.makedirs(o, exist_ok=True)
                cv2.imwrite(os.path.join(o, f"{m}.png"), cv2.cvtColor(sr, cv2.COLOR_RGB2BGR))
                r = det.predict(sr[..., ::-1], imgsz=1024, conf=0.25, verbose=False)[0]
                names = [r.names[int(c)] for c in r.obb.cls] if r.obb is not None else []
                detections[f"{port}/{date}/{m}"] = {
                    "boxes": r.obb.xyxyxyxy.cpu().numpy().round(1).tolist() if r.obb is not None else [],
                    "classes": names, "conf": r.obb.conf.cpu().numpy().round(3).tolist() if r.obb is not None else []}
                rows.append(dict(port=port, date=date, method=m, lr_consistency=lr_consistency(sr, lr),
                                 n_det=len(names), n_ship=names.count("ship"),
                                 n_storage_tank=names.count("storage tank"), n_harbor=names.count("harbor"),
                                 n_large_vehicle=names.count("large vehicle")))
            print(port, date, flush=True)
        dates = sorted({d for d, _ in srs})
        for d1, d2 in itertools.combinations(dates, 2):
            b1, b2 = srs[(d1, "bicubic")].astype(np.float32), srs[(d2, "bicubic")].astype(np.float32)
            unchanged = np.abs(b1 - b2).mean(-1) < 3
            for m in a.methods:
                if (d1, m) not in srs:
                    continue
                diff = np.abs(srs[(d1, m)].astype(np.float32) - srs[(d2, m)].astype(np.float32)).mean(-1)
                trows.append(dict(port=port, d1=d1, d2=d2, method=m, unchanged_frac=unchanged.mean(),
                                  instability=diff[unchanged].mean()))
    out = os.path.join(ROOT, "results", "metrics")
    os.makedirs(out, exist_ok=True)
    df, tdf = pd.DataFrame(rows), pd.DataFrame(trows)
    df.to_csv(os.path.join(out, "ports_per_image.csv"), index=False)
    tdf.to_csv(os.path.join(out, "ports_temporal.csv"), index=False)
    json.dump(detections, open(os.path.join(out, "ports_detections.json"), "w"))
    base = tdf[tdf.method == "bicubic"].set_index(["port", "d1", "d2"]).instability
    tdf["excess_instability"] = tdf.instability.values - base.loc[list(zip(tdf.port, tdf.d1, tdf.d2))].values
    summ = df.groupby("method")[["lr_consistency", "n_det", "n_ship", "n_storage_tank", "n_harbor"]].mean().join(
        tdf.groupby("method")[["instability", "excess_instability"]].mean())
    summ.to_csv(os.path.join(out, "ports_summary.csv"))
    print(summ.round(3).to_string())


if __name__ == "__main__":
    main()
